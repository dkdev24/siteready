// Agent-readiness generator for Next.js (App Router), written into a site by
// `siteready enhance` and run from its `postbuild` script. After `next build`
// it turns every prerendered page into a markdown mirror (`public/<route>.md`)
// and writes an `llms.txt` index, so agents can fetch clean markdown instead of
// HTML. Source of truth is the build's own output (`.next/prerender-manifest.json`
// plus the prerendered HTML), so it works whatever the site's content source is.
//
// Rules this file keeps:
//  - It never fails the build: every error becomes a warning and the exit code is 0.
//  - It only deletes/overwrites files it wrote itself (they end with MARKER); a
//    `.md` or `llms.txt` you wrote by hand is left alone and counted as skipped.
//  - Node builtins only, so it runs in any CI regardless of the site's package type.
//
// Only prerendered (static) pages are covered; server-rendered routes have no HTML
// at build time. Generated files are rebuilt every build: add them to .gitignore.
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const MARKER = "<!-- generated by siteready agent-readiness -->";
const LLMS_SPLIT_CHARS = 30000; // llms.txt convention: split into per-section files above ~30KB
const MIN_BODY_CHARS = 20;

const SKIP_TAGS = new Set(["script", "style", "template", "noscript", "svg", "canvas", "iframe", "video", "audio", "button", "input", "select", "textarea", "dialog", "head", "object", "embed"]);
const VOID_TAGS = new Set(["br", "hr", "img", "input", "meta", "link", "source", "track", "wbr", "col", "area", "base", "embed", "param"]);
const BLOCK_TAGS = new Set(["div", "section", "article", "aside", "header", "footer", "main", "nav", "figure", "figcaption", "details", "summary", "form", "fieldset", "address", "dl", "dd", "dt"]);
const CHROME_TAGS = new Set(["header", "nav", "footer", "aside"]); // dropped when there is no <main>
const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", mdash: "—", ndash: "–", hellip: "…", laquo: "«", raquo: "»", copy: "©", reg: "®", trade: "™", middot: "·", bull: "•", rarr: "→", larr: "←", times: "×", lsquo: "‘", rsquo: "’", ldquo: "“", rdquo: "”" };

export function decodeEntities(s) {
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, e) => {
    if (e[0] === "#") {
      const code = e[1].toLowerCase() === "x" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      try {
        return String.fromCodePoint(code);
      } catch {
        return m;
      }
    }
    return ENTITIES[e.toLowerCase()] ?? m;
  });
}

// --- tiny HTML tree ---------------------------------------------------------

const TAG_RE = /<!--[\s\S]*?-->|<(\/?)([a-zA-Z][\w:-]*)((?:"[^"]*"|'[^']*'|[^'">])*?)(\/?)>|[^<]+|</g;

function parseAttrs(raw) {
  const attrs = {};
  for (const m of raw.matchAll(/([^\s=/"']+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+)))?/g)) {
    attrs[m[1].toLowerCase()] = decodeEntities(m[2] ?? m[3] ?? m[4] ?? "");
  }
  return attrs;
}

export function parseHtml(html) {
  const root = { tag: "#root", attrs: {}, children: [] };
  const stack = [root];
  TAG_RE.lastIndex = 0;
  let m;
  while ((m = TAG_RE.exec(html))) {
    const [token, closing, name, rawAttrs, selfClose] = m;
    if (token.startsWith("<!--")) continue; // also drops React's <!-- --> / <!--$--> markers
    const top = stack[stack.length - 1];
    if (!name) {
      if (token !== "<") top.children.push({ text: token });
      continue;
    }
    const tag = name.toLowerCase();
    if (closing) {
      for (let i = stack.length - 1; i > 0; i--) {
        if (stack[i].tag === tag) {
          stack.length = i;
          break;
        }
      }
      continue;
    }
    const node = { tag, attrs: parseAttrs(rawAttrs), children: [] };
    top.children.push(node);
    if (tag === "script" || tag === "style") {
      // raw-text elements: swallow up to the closing tag so JS/CSS never leaks into text
      const end = html.toLowerCase().indexOf(`</${tag}`, TAG_RE.lastIndex);
      TAG_RE.lastIndex = end === -1 ? html.length : html.indexOf(">", end) + 1;
      continue;
    }
    if (!selfClose && !VOID_TAGS.has(tag)) stack.push(node);
  }
  return root;
}

function find(node, pred) {
  if (node.tag && pred(node)) return node;
  for (const c of node.children ?? []) {
    const hit = find(c, pred);
    if (hit) return hit;
  }
  return null;
}

function textOf(node) {
  if (node.text !== undefined) return decodeEntities(node.text);
  if (SKIP_TAGS.has(node.tag)) return "";
  return node.children.map(textOf).join("");
}

function isHidden(node) {
  return "hidden" in node.attrs || node.attrs["aria-hidden"] === "true";
}

// --- HTML -> markdown -------------------------------------------------------

// Elements that must not run into their neighbours when flattened to one line.
const LINE_TAGS = new Set([...BLOCK_TAGS, "p", "li", "ul", "ol", "tr", "td", "th", "h1", "h2", "h3", "h4", "h5", "h6", "table", "tbody", "thead", "blockquote", "pre"]);

// Joins inline fragments, keeping adjacent links apart (`</a><a>` carries no whitespace in React output).
function join(parts) {
  let out = "";
  for (const part of parts) {
    if (out.endsWith(")") && part.startsWith("[")) out += " ";
    out += part;
  }
  return out;
}


export function htmlToMarkdown(html, { origin = "" } = {}) {
  const tree = parseHtml(html);
  const main = find(tree, (n) => n.tag === "main") ?? find(tree, (n) => n.tag === "body") ?? tree;
  const dropChrome = main.tag !== "main";

  const abs = (href) => (origin && href.startsWith("/") && !href.startsWith("//") ? origin + href : href);

  function inline(node, ctx) {
    if (node.text !== undefined) {
      const t = decodeEntities(node.text);
      return ctx.pre ? t : t.replace(/\s+/g, " ");
    }
    if (SKIP_TAGS.has(node.tag) || isHidden(node) || ctx.skip === node) return "";
    const kids = () => join(node.children.map((c) => inline(c, ctx)));
    switch (node.tag) {
      case "br":
        return "  \n";
      case "strong":
      case "b": {
        const t = kids().trim();
        return t ? `**${t}**` : "";
      }
      case "em":
      case "i": {
        const t = kids().trim();
        return t ? `*${t}*` : "";
      }
      case "code": {
        const t = textOf(node);
        return ctx.pre || !t.trim() ? t : "`" + t.replace(/`/g, "'") + "`";
      }
      case "a": {
        const href = (node.attrs.href ?? "").trim();
        // A card link ("<a><h3>Title</h3><p>blurb</p></a>"): link the heading, keep the blurb as text.
        const heading = find(node, (n) => /^h[1-6]$/.test(n.tag));
        const text = (heading ? inline(heading, ctx) : kids()).replace(/\s+/g, " ").trim();
        const rest = heading ? join(node.children.map((c) => inline(c, { ...ctx, skip: heading }))).replace(/\s+/g, " ").trim() : "";
        if (!text) return rest;
        const link = !href || href.startsWith("#") || /^(javascript|mailto|tel):/i.test(href) ? text : `[${text}](${abs(href)})`;
        return rest ? `${link}: ${rest}` : link;
      }
      case "img": {
        const alt = (node.attrs.alt ?? "").trim();
        let src = node.attrs.src ?? "";
        const next = src.match(/[?&]url=([^&]+)/);
        if (src.startsWith("/_next/image") && next) src = decodeURIComponent(next[1]);
        return alt && src && !src.startsWith("data:") ? `![${alt}](${abs(src)})` : "";
      }
      default:
        return LINE_TAGS.has(node.tag) ? ` ${kids()} ` : kids();
    }
  }

  function blocks(node, ctx) {
    const out = [];
    let run = []; // consecutive inline nodes become one paragraph
    const flush = () => {
      const t = join(run.map((c) => inline(c, ctx))).replace(/[ \t]+\n/g, "\n").trim();
      if (t) out.push(t);
      run = [];
    };
    for (const c of node.children) {
      if (c.text !== undefined) {
        run.push(c);
        continue;
      }
      if (SKIP_TAGS.has(c.tag) || isHidden(c) || (dropChrome && CHROME_TAGS.has(c.tag))) continue;
      const tag = c.tag;
      if (/^h[1-6]$/.test(tag)) {
        flush();
        const t = inline(c, ctx).replace(/\s+/g, " ").trim();
        if (t) out.push(`${"#".repeat(Number(tag[1]))} ${t}`);
      } else if (tag === "p") {
        flush();
        const t = inline(c, ctx).trim();
        if (t) out.push(t);
      } else if (tag === "pre") {
        flush();
        const code = textOf(c).replace(/\n$/, "");
        const lang = (find(c, (n) => n.tag === "code")?.attrs.class ?? "").match(/language-([\w+-]+)/)?.[1] ?? "";
        if (code.trim()) out.push("```" + lang + "\n" + code + "\n```");
      } else if (tag === "ul" || tag === "ol") {
        flush();
        const l = list(c, ctx, 0);
        if (l) out.push(l);
      } else if (tag === "blockquote") {
        flush();
        const inner = blocks(c, ctx).join("\n\n");
        if (inner) out.push(inner.split("\n").map((l) => `> ${l}`.trimEnd()).join("\n"));
      } else if (tag === "hr") {
        flush();
        out.push("---");
      } else if (tag === "table") {
        flush();
        const t = table(c, ctx);
        if (t) out.push(t);
      } else if (BLOCK_TAGS.has(tag) || tag === "li" || tag === "tr" || tag === "tbody" || tag === "thead" || tag === "body" || tag === "html") {
        flush();
        out.push(...blocks(c, ctx).map((b) => (tag === "dt" ? `**${b}**` : b)));
      } else {
        run.push(c);
      }
    }
    flush();
    return out;
  }

  function list(node, ctx, depth) {
    const lines = [];
    let n = 0;
    for (const li of node.children) {
      if (li.tag !== "li" || isHidden(li)) continue;
      n += 1;
      const bullet = node.tag === "ol" ? `${n}.` : "-";
      const own = [];
      const nested = [];
      for (const c of li.children) {
        if (c.tag === "ul" || c.tag === "ol") nested.push(list(c, ctx, depth + 1));
        else own.push(c);
      }
      const text = blocks({ children: own }, ctx).join(" ").replace(/\s*\n\s*/g, " ").trim();
      lines.push(`${"  ".repeat(depth)}${bullet} ${text}`.trimEnd());
      for (const sub of nested) if (sub) lines.push(sub);
    }
    return lines.join("\n");
  }

  function table(node, ctx) {
    const rows = [];
    const walk = (n) => {
      for (const c of n.children) {
        if (c.tag === "tr") rows.push(c.children.filter((x) => x.tag === "th" || x.tag === "td").map((cell) => inline(cell, ctx).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim()));
        else if (c.tag === "thead" || c.tag === "tbody" || c.tag === "tfoot") walk(c);
      }
    };
    walk(node);
    if (!rows.length || !rows[0].length) return "";
    const width = Math.max(...rows.map((r) => r.length));
    const pad = (r) => Array.from({ length: width }, (_, i) => r[i] ?? "");
    const line = (r) => `| ${pad(r).join(" | ")} |`;
    return [line(rows[0]), line(Array(width).fill("---")), ...rows.slice(1).map(line)].join("\n");
  }

  return blocks(main, {}).join("\n\n").replace(/\n{3,}/g, "\n\n").trim();
}

// --- page metadata ----------------------------------------------------------

function metaContent(tree, key, attr = "name") {
  return find(tree, (n) => n.tag === "meta" && (n.attrs[attr] ?? "").toLowerCase() === key)?.attrs.content?.trim() ?? "";
}

export function pageMeta(html) {
  const tree = parseHtml(html);
  const head = find(tree, (n) => n.tag === "head") ?? tree;
  const title = textOf(find(head, (n) => n.tag === "title") ?? { children: [] }).trim();
  const canonical = find(head, (n) => n.tag === "link" && (n.attrs.rel ?? "").toLowerCase() === "canonical")?.attrs.href ?? "";
  return {
    title,
    description: metaContent(head, "description") || metaContent(head, "og:description", "property"),
    siteName: metaContent(head, "og:site_name", "property"),
    canonical,
    canonicalOrigin: originOf(canonical) || originOf(metaContent(head, "og:url", "property")),
    noindex: /noindex/i.test(metaContent(head, "robots")),
  };
}

function originOf(url) {
  try {
    return url ? new URL(url).origin : "";
  } catch {
    return "";
  }
}

// --- file helpers -----------------------------------------------------------

async function isOurs(file) {
  try {
    return (await readFile(file, "utf8")).trimEnd().endsWith(MARKER);
  } catch {
    return false;
  }
}

// Writes only if the target is absent or ours. Returns "written" | "skipped".
async function writeOwned(file, content) {
  if (existsSync(file) && !(await isOurs(file))) return "skipped";
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content.trimEnd() + "\n\n" + MARKER + "\n", "utf8");
  return "written";
}

async function* walk(dir) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else yield p;
  }
}

function groupLabel(segment) {
  if (!segment) return "Pages";
  if (/^[a-z]{2}(-[A-Za-z]{2})?$/.test(segment)) {
    try {
      const name = new Intl.DisplayNames(["en"], { type: "language" }).of(segment);
      if (name && name !== segment) return name;
    } catch {}
  }
  return segment.replace(/[-_]+/g, " ").replace(/^./, (c) => c.toUpperCase());
}

function llmsFile({ name, summary, groups }) {
  const lines = [`# ${name}`, ""];
  if (summary) lines.push(`> ${summary}`, "");
  for (const [label, entries] of groups) {
    lines.push(`## ${label}`, "", ...entries, "");
  }
  return lines.join("\n").trimEnd();
}

// --- main -------------------------------------------------------------------

export async function generate(cwd = process.cwd(), { log = console.log, warn = console.warn } = {}) {
  const manifestPath = path.join(cwd, ".next", "prerender-manifest.json");
  const publicDir = path.join(cwd, "public");
  if (!existsSync(manifestPath)) {
    warn("agent-readiness: .next/prerender-manifest.json not found (run after `next build`); nothing generated.");
    return;
  }
  let routes;
  try {
    const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    if (typeof manifest.routes !== "object" || manifest.routes === null) throw new Error("no `routes` object");
    routes = Object.entries(manifest.routes)
      .filter(([route, info]) => info.routeType === "page" && (info.initialStatus ?? 200) === 200 && !route.startsWith("/_") && !path.posix.basename(route).includes("."))
      .map(([route]) => route)
      .sort();
  } catch (err) {
    warn(`agent-readiness: unrecognized .next/prerender-manifest.json format (${err.message}); nothing generated.`);
    return;
  }

  const pages = [];
  let skippedMd = 0;
  const written = new Set();
  for (const route of routes) {
    const htmlFile = path.join(cwd, ".next", "server", "app", route === "/" ? "index.html" : `${route.slice(1)}.html`);
    if (!existsSync(htmlFile)) continue;
    const html = await readFile(htmlFile, "utf8");
    const meta = pageMeta(html);
    if (meta.noindex) continue;
    pages.push({ route, html, meta });
  }
  if (!pages.length) {
    warn("agent-readiness: no prerendered pages found; nothing generated.");
    return;
  }

  // AGENT_READINESS_ORIGIN: an origin URL, or `none` to force root-relative links (local scans, where
  // absolute production URLs would make a scanner follow the live site instead of the build).
  const override = process.env.AGENT_READINESS_ORIGIN?.trim();
  const origin = override === "none" ? "" : override?.replace(/\/$/, "") || pages.map((p) => p.meta.canonicalOrigin).find(Boolean) || "";
  if (!origin && override !== "none") warn("agent-readiness: no canonical/og:url origin found, so links are root-relative. Set `alternates.canonical` in your metadata, or AGENT_READINESS_ORIGIN, for absolute links.");
  const url = (p) => `${origin}${p}`;
  const mdPathFor = (route) => (route === "/" ? "/index.md" : `${route}.md`);

  const llmsDirective = (scope) => `> For the complete documentation index, see [llms.txt](${url(scope)}).`;
  const sectionOf = (route) => route.split("/")[1] ?? "";
  const hasRootRoute = pages.some((p) => p.route === "/");

  const home = pages.find((p) => p.route === "/") ?? [...pages].sort((a, b) => a.route.length - b.route.length)[0];
  // A page's mirror lives at its canonical URL + `.md` (what an agent gets by appending `.md` to the URL
  // it was given), which differs from the route when the site rewrites, e.g. an unprefixed default locale.
  const mdRouteOf = ({ route, meta }) => {
    try {
      const canon = new URL(meta.canonical);
      if (override === "none" || (origin && canon.origin === origin)) return canon.pathname.length > 1 ? canon.pathname.replace(/\/$/, "") : "/";
    } catch {}
    return route;
  };
  const taken = new Set();
  const entries = [];
  for (const page of pages) {
    const { route, html, meta } = page;
    const mdRoute = mdRouteOf(page);
    if (taken.has(mdRoute)) continue;
    const body = htmlToMarkdown(html, { origin });
    if (body.length < MIN_BODY_CHARS) continue;
    const title = body.match(/^#\s+(.+)$/m)?.[1].trim() || meta.title || route;
    const md = [llmsDirective("/llms.txt"), "", /^#\s/m.test(body) ? body : `# ${title}\n\n${body}`].join("\n");
    taken.add(mdRoute);
    const file = path.join(publicDir, mdPathFor(mdRoute).slice(1));
    const result = await writeOwned(file, md);
    if (result === "skipped") skippedMd += 1;
    else written.add(path.resolve(file));
    // A site-wide description repeated on every page says nothing about this page.
    const description = route !== home.route && meta.description === home.meta.description ? "" : meta.description;
    entries.push({ route, title, description, mdUrl: url(mdPathFor(mdRoute)), skipped: result === "skipped" });
  }

  // llms.txt: skip if a route handler or a hand-written file already owns it.
  const llmsPath = path.join(publicDir, "llms.txt");
  const routeHandler = ["app", "src/app"].some((d) => existsSync(path.join(cwd, d, "llms.txt")));
  let llmsStatus = "skipped";
  if (!routeHandler && !(existsSync(llmsPath) && !(await isOurs(llmsPath)))) {
    const name = home.meta.siteName || home.meta.title || "Site";
    const summary = home.meta.description;
    const bySection = new Map();
    for (const e of entries) {
      const key = sectionOf(e.route);
      if (!bySection.has(key)) bySection.set(key, []);
      bySection.get(key).push(`- [${e.title}](${e.mdUrl})${e.description ? `: ${e.description}` : ""}`);
    }
    const groups = [...bySection].map(([key, lines]) => [groupLabel(key), lines]);
    const flat = llmsFile({ name, summary, groups });
    if (flat.length <= LLMS_SPLIT_CHARS || bySection.size < 2) {
      llmsStatus = await writeOwned(llmsPath, flat);
      if (llmsStatus === "written") written.add(path.resolve(llmsPath));
    } else {
      const index = [];
      for (const [key, lines] of bySection) {
        const label = groupLabel(key);
        const scoped = path.join(publicDir, key || "_root", "llms.txt");
        if (!key) {
          index.push(...lines);
          continue;
        }
        const r = await writeOwned(scoped, llmsFile({ name: `${name}: ${label}`, summary: `${label} pages. See ${url("/llms.txt")} for the site index.`, groups: [[label, lines]] }));
        if (r === "written") written.add(path.resolve(scoped));
        index.push(`- [${label}](${url(`/${key}/llms.txt`)})`);
      }
      llmsStatus = await writeOwned(llmsPath, llmsFile({ name, summary, groups: [["Sections", index]] }));
      if (llmsStatus === "written") written.add(path.resolve(llmsPath));
    }
  }

  // Remove files we wrote on an earlier build that no longer correspond to a page.
  let removed = 0;
  for await (const file of walk(publicDir)) {
    if (!/\.md$|[\\/]llms\.txt$/.test(file) || written.has(path.resolve(file))) continue;
    if (await isOurs(file)) {
      await rm(file, { force: true });
      removed += 1;
    }
  }

  log(`agent-readiness: ${written.size} file(s) written (${entries.length - skippedMd} .md, llms.txt ${llmsStatus}), ${skippedMd} existing .md left alone, ${removed} stale removed.`);
  if (!hasRootRoute) warn("agent-readiness: no prerendered `/` page (the root is probably redirected or rewritten), so no /index.md was generated.");
  if (routeHandler) warn("agent-readiness: an app/llms.txt route handler exists; llms.txt left to it.");
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    await generate();
  } catch (err) {
    console.warn(`agent-readiness: skipped after an error (${err.message}). The build is unaffected.`);
  }
  process.exitCode = 0;
}
